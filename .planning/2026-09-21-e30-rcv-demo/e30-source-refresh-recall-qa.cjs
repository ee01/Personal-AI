const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { chromium } = require('/Users/Esone/git/personal-ai/desktop-app/node_modules/playwright');
const { pathToFileURL } = require('node:url');
const target = '/Users/Esone/git/personal-ai/docs/progressing/memory-source-refresh-recall-demo.html';
const html = fs.readFileSync(target, 'utf8');
for (const [, source] of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(source);
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1280,height:1080}});
 const errors=[]; const remoteRequests=[];
 page.on('pageerror', e=>errors.push(e.message));
 page.on('request', r=>{if (/^https?:/.test(r.url())) remoteRequests.push(r.url());});
 try {
  await page.goto(pathToFileURL(target).href);
  assert.equal(await page.locator('#refresh-badge').textContent(),'仅记住链接');
  assert.equal(await page.locator('#checked-at').textContent(),'尚无成功检查');
  assert.match(await page.locator('.answer').textContent(),/你在与 Sandy 的私聊中问过/);
  assert.equal(await page.locator('#evidence-6').isVisible(),false);
  await page.locator('[data-source="6"]').click();
  assert.equal(await page.locator('#evidence-6').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.activeElement.id),'evidence-6');
  await page.locator('#expand-sources').click();
  assert.equal(await page.locator('#evidence-6').isVisible(),false);
  await page.locator('#simulate-change').click();
  assert.equal(await page.locator('#refresh-badge').textContent(),'正在检查');
  assert.equal(await page.locator('#checked-at').textContent(),'尚无成功检查');
  await page.waitForFunction(()=>document.querySelector('#refresh-badge').textContent==='已更新');
  assert.equal(await page.locator('#version').textContent(),'v1 · 示例');
  const updatedAt = await page.locator('#updated-at').textContent();
  const firstSuccessfulCheck = await page.locator('#checked-at').textContent();
  await page.locator('#simulate-failure').click();
  await page.waitForFunction(()=>document.querySelector('#refresh-badge').textContent==='检查失败 · 保留旧版');
  assert.equal(await page.locator('#checked-at').textContent(),firstSuccessfulCheck, 'Failed check must preserve last successful check time');
  assert.equal(await page.locator('#updated-at').textContent(),updatedAt);
  assert.equal(await page.locator('#version').textContent(),'v1 · 示例');
  assert.equal(await page.locator('#source-excerpt').isVisible(),true);
  await page.locator('#simulate-unchanged').click();
  await page.waitForFunction(()=>document.querySelector('#refresh-badge').textContent==='已检查 · 内容未变化');
  const unchangedSuccessfulCheck = await page.locator('#checked-at').textContent();
  assert.notEqual(unchangedSuccessfulCheck,firstSuccessfulCheck);
  assert.equal(await page.locator('#updated-at').textContent(),updatedAt);
  await page.locator('#simulate-failure').click();
  await page.waitForFunction(()=>document.querySelector('#refresh-badge').textContent==='检查失败 · 保留旧版');
  assert.equal(await page.locator('#checked-at').textContent(),unchangedSuccessfulCheck, 'Failure after unchanged success must preserve successful check time');
  await page.locator('summary').click();
  assert.equal(await page.locator('.steps').isVisible(),true);
  for(const citation of await page.locator('[data-source]').all()) {
    await citation.click();
    const id=await citation.getAttribute('data-source');
    assert.equal(await page.locator('#evidence-'+id).isVisible(),true);
  }
  await page.screenshot({path:'/tmp/e30-source-refresh-recall-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:'/tmp/e30-source-refresh-recall-mobile.png',fullPage:true});
  await page.locator('#simulate-change').click();
  await page.waitForFunction(()=>document.querySelector('#refresh-badge').textContent==='发现版本变化 · 刷新中');
  assert.equal(await page.locator('#checked-at').textContent(),unchangedSuccessfulCheck);
  await page.waitForFunction(()=>document.querySelector('#refresh-badge').textContent==='已更新');
  assert.equal(await page.locator('#version').textContent(),'v2 · 示例');
  assert.notEqual(await page.locator('#checked-at').textContent(),unchangedSuccessfulCheck);
  await page.locator('#simulate-change').click();
  await page.locator('#reset-refresh').click();
  await page.waitForTimeout(1700);
  assert.equal(await page.locator('#refresh-badge').textContent(),'仅记住链接');
  assert.equal(await page.locator('#checked-at').textContent(),'尚无成功检查');
  assert.equal(await page.locator('#source-excerpt').isVisible(),false);
  assert.deepEqual(errors,[]);
  assert.deepEqual(remoteRequests,[]);
  console.log(JSON.stringify({result:'PASS',checks:['JavaScript syntax','Esone explicitly attributed as question author','success then failure preserves last successful check time','unchanged success then failure preserves last successful check time','in-flight refresh preserves last successful check time','unchanged content preserves version/time','failure preserves old body/version','reset cancels pending transition','all answer citations reveal and focus evidence','show/hide extra source','pipeline disclosure','390px no horizontal overflow','no page errors','no remote requests'],screenshots:['/tmp/e30-source-refresh-recall-desktop.png','/tmp/e30-source-refresh-recall-mobile.png']},null,2));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
